package aws

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"
	"time"
)

// The cleanup runs one of the two established account wiping tools as an
// external process, fully non-interactive (all confirmation prompts disabled,
// dry-run disabled). The generated tool configuration and the complete tool
// output are persisted in Config.WorkDir per account and per run, so every
// cleanup is auditable after the fact.
//
// Both configurations exclude the bootstrap roles (organization access +
// sandbox role) so the account remains manageable after the wipe; everything
// else is removed. The scps live in the management account and are therefore
// never affected by the nuke.

// awsNukeTemplate renders the config for github.com/ekristen/aws-nuke (v3).
// The blocklist is a mandatory aws-nuke safety feature: it refuses to run if
// the target account is listed there, and refuses to run with an empty list.
const awsNukeTemplate = `# generated by cloudjam sandbox - regenerated on every cleanup run
blocklist:
{{- range .Blocklist }}
  - "{{ . }}"
{{- end }}

regions:
  - global
{{- range .Regions }}
  - {{ . }}
{{- end }}

accounts:
  "{{ .Account }}":
    filters:
      IAMAccountAlias:
        - "{{ .Alias }}"
      IAMRole:
        - "{{ .OrganizationRole }}"
        - "{{ .SandboxRole }}"
      IAMRolePolicyAttachment:
        - "{{ .OrganizationRole }} -> AdministratorAccess"
        - "{{ .SandboxRole }} -> AdministratorAccess"
`

// cloudNukeTemplate renders the config for github.com/gruntwork-io/cloud-nuke.
const cloudNukeTemplate = `# generated by cloudjam sandbox - regenerated on every cleanup run
IAMRoles:
  exclude:
    names_regex:
      - "^{{ .OrganizationRole }}$"
      - "^{{ .SandboxRole }}$"
`

type nukeParameters struct {
	Account          string
	Alias            string
	Blocklist        []string
	Regions          []string
	OrganizationRole string
	SandboxRole      string
}

// clean wipes the account with the configured tool and returns the path of
// the persisted tool log (also on failure, for inspection).
func (r *Repository) clean(ctx context.Context, id string) (string, error) {
	binary, err := exec.LookPath(r.config.NukeBinary)
	if err != nil {
		return "", fmt.Errorf("cleanup tool %q not found (install %s): %w", r.config.NukeBinary, r.config.Nuke, err)
	}

	config, _, err := r.assume(ctx, id, r.config.SandboxRole)
	if err != nil {
		return "", err
	}
	session, err := config.Credentials.Retrieve(ctx)
	if err != nil {
		return "", fmt.Errorf("failed to retrieve cleanup credentials: %w", err)
	}

	parameters := nukeParameters{
		Account:          id,
		Alias:            r.alias(id),
		Blocklist:        append([]string{r.management}, r.config.Blocklist...),
		Regions:          r.config.Regions,
		OrganizationRole: r.config.OrganizationRole,
		SandboxRole:      r.config.SandboxRole,
	}

	directory := filepath.Join(r.config.WorkDir, id)
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return "", fmt.Errorf("failed to create work directory: %w", err)
	}
	stamp := time.Now().UTC().Format("20060102-150405")
	configPath := filepath.Join(directory, fmt.Sprintf("%s-%s.yaml", r.config.Nuke, stamp))
	logPath := filepath.Join(directory, fmt.Sprintf("%s-%s.log", r.config.Nuke, stamp))

	var configTemplate string
	var arguments []string
	switch r.config.Nuke {
	case NukeToolAWSNuke:
		configTemplate = awsNukeTemplate
		// --no-prompt disables the interactive confirmation, --prompt-delay
		// shortens the mandatory pre-run sleep, --no-dry-run performs the
		// actual removal instead of only listing resources.
		arguments = []string{"run", "--config", configPath, "--no-prompt", "--prompt-delay", "3", "--no-dry-run"}
	case NukeToolCloudNuke:
		configTemplate = cloudNukeTemplate
		// --force disables all interactive confirmations.
		arguments = []string{"aws", "--force", "--config", configPath}
		for _, region := range r.config.Regions {
			arguments = append(arguments, "--region", region)
		}
	default:
		return "", fmt.Errorf("unknown cleanup tool %q", r.config.Nuke)
	}

	rendered, err := template.New("nuke").Parse(configTemplate)
	if err != nil {
		return "", fmt.Errorf("failed to parse cleanup config template: %w", err)
	}
	file, err := os.Create(configPath)
	if err != nil {
		return "", fmt.Errorf("failed to create cleanup config: %w", err)
	}
	if err := rendered.Execute(file, parameters); err != nil {
		file.Close()
		return "", fmt.Errorf("failed to render cleanup config: %w", err)
	}
	file.Close()

	log, err := os.Create(logPath)
	if err != nil {
		return "", fmt.Errorf("failed to create cleanup log: %w", err)
	}
	defer log.Close()

	command := exec.CommandContext(ctx, binary, arguments...)
	command.Stdout = log
	command.Stderr = log
	command.Env = append(os.Environ(),
		"AWS_ACCESS_KEY_ID="+session.AccessKeyID,
		"AWS_SECRET_ACCESS_KEY="+session.SecretAccessKey,
		"AWS_SESSION_TOKEN="+session.SessionToken,
		"AWS_DEFAULT_REGION="+r.config.Regions[0],
	)

	r.config.Logger.Info("running cleanup tool", "account", id, "command", binary, "config", configPath, "log", logPath)
	if err := command.Run(); err != nil {
		return logPath, fmt.Errorf("cleanup tool failed: %w", err)
	}
	return logPath, nil
}
